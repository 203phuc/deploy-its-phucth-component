export interface IconProps {
  /**
   * The size of the icon in pixels
   * @default 24
   */
  size?: number;

  /**
   * The color of the icon
   * @default 'currentColor'
   */
  color?: string;

  /**
   * The stroke width of the icon
   */
  strokeWidth?: number;

  /**
   * Additional class name for the icon
   */
  className?: string;
}
